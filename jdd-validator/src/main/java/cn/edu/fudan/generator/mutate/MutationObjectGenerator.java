    private static String getType(Object value) {
        if (value instanceof Integer || value == int.class) {
            return "int";
        } else if (value instanceof Double || value == double.class) {
            return "double";
        } else if (value instanceof Boolean || value == boolean.class) {
            return "boolean";
        } else if (value instanceof Character || value == char.class) {
            return "char";
        } else if (value instanceof Byte || value == byte.class) {
            return "byte";
        } else if (value instanceof Short || value == short.class) {
            return "short";
        } else if (value instanceof Long || value == long.class) {
            return "long";
        } else if (value instanceof Float || value == float.class) {
            return "float";
        } else {
            return "unknown";
        }
    }
