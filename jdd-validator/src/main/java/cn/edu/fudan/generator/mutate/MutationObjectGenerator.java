    public static Object mutatePrimitiveType(Class<?> fldType) {
        Random sourceOfRandomness = new Random();
        Object mutatedObj = null;
        switch (getType(fldType)) {
            case "int":
                mutatedObj = CommonUtils.generateRandomInt(0, 10);
                break;
            case "double":
                mutatedObj = CommonUtils.generateRandomDouble(0.0, 10.0);
                break;
            case "boolean":
                mutatedObj = CommonUtils.generateRandomBoolean();
                break;
            case "char":
                mutatedObj = CommonUtils.generateRandomChar();
                break;
            case "byte":
                mutatedObj = (byte) CommonUtils.generateRandomInt(0, 127);
                break;
            case "short":
                mutatedObj = CommonUtils.generateRandomShort((short)0, (short)10);
                break;
            case "long":
                mutatedObj = CommonUtils.generateRandomLong(0L, 10L);
                break;
            case "float":
                mutatedObj = CommonUtils.generateRandomFloat(0.0f, 10.0f);
                break;
            default:
                LogUtils.error("In `MutationObjectGenerator.mutatePrimitiveType`: The value is not a basic seedType. return null.");
                break;
        }

        return mutatedObj;
    }

